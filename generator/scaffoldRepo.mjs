function mantleConfigTs(recipe, resolved) {
  const m = recipe.mantle ?? {};
  const config = {
    title: recipe.site.title,
    models: resolved.models.map((x) => x.id),
    defaultModel: resolved.defaultModel,
    ...(m.defaultCamera ? { defaultCamera: m.defaultCamera } : {}),
    ...(m.viewPresets ? { viewPresets: m.viewPresets } : {}),
    ...(m.comparisonPresets !== undefined ? { comparisonPresets: m.comparisonPresets } : {}),
  };
  // The interface is copied from the checked-in viewer/src/generated/
  // mantleConfig.ts, so the two can't drift.
  const src = readFileSync(path.join(VIEWER_ROOT, 'src', 'generated', 'mantleConfig.ts'), 'utf8');
  const types = src.slice(0, src.indexOf('/**\n * The file generator/scaffoldRepo.mjs'));
  return `${types}// Generated by generator/scaffoldRepo.mjs from this repo's own recipe.json --
// edit that and regenerate (--update) rather than editing this file.
export const MANTLE_CONFIG: MantleConfig = ${JSON.stringify(config, null, 2)};
`;
}

