#!/usr/bin/env node
/**
 * Turn a validated Viewer Recipe into a standalone, minimal repo: the
 * generic engine and globe wrapper (viewer/src/core/, viewer/src/globe/),
 * no dev tooling, no private submodule, no local copy of data -- everything
 * else comes from the recipe's own dataHost at runtime. See
 * docs/plans/consider-this-general-question-virtual-kay.md.
 *
 *   node generator/scaffoldRepo.mjs recipe.json outDir
 */
import {
  readFileSync, writeFileSync, mkdirSync, cpSync,
} from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { validateRecipe } from './validateRecipe.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.join(HERE, '..');
const VIEWER_ROOT = path.join(REPO_ROOT, 'viewer');

function loadJson(p) {
  return JSON.parse(readFileSync(p, 'utf8'));
}

function escapeHtml(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function configTs(recipe, resolved) {
  return `import type { GlobeTool } from '../globe/globeUi';

export interface GlobeConfig {
  modelId: string;
  title: string;
  tools: GlobeTool[];
}

// Generated by generator/scaffoldRepo.mjs from this repo's own recipe.json --
// hand-edit that and re-run the generator rather than editing this file
// directly, or the two will silently disagree.
export const GLOBE_CONFIG: GlobeConfig = {
  modelId: ${JSON.stringify(resolved.modelId)},
  title: ${JSON.stringify(recipe.site.title)},
  tools: ${JSON.stringify(recipe.ui.tools)} as GlobeTool[],
};
`;
}

function packageJson(site, viewerPkg) {
  return `${JSON.stringify({
    name: site.repoName,
    private: true,
    version: '1.0.0',
    type: 'module',
    scripts: { dev: 'vite', build: 'vite build', preview: 'vite preview' },
    dependencies: {
      three: viewerPkg.dependencies.three,
      'lil-gui': viewerPkg.dependencies['lil-gui'],
    },
    devDependencies: {
      vite: viewerPkg.devDependencies.vite,
      typescript: viewerPkg.devDependencies.typescript,
      '@types/three': viewerPkg.devDependencies['@types/three'],
    },
  }, null, 2)}\n`;
}

function viteConfigTs() {
  return `import { defineConfig } from 'vite';

// GitHub Pages serves a project site under /<repo>/, not the domain root --
// VITE_BASE is set by the deploy workflow below, from the repo's own name,
// so this works unmodified whatever the site was named. Do not hardcode a
// path here (see the main Geode repo's own vite.config.ts for why).
export default defineConfig({
  base: process.env.VITE_BASE ?? '/',
  server: { port: 5173 },
  build: { target: 'es2022' },
});
`;
}

function tsconfigJson() {
  return `${JSON.stringify({
    compilerOptions: {
      target: 'ES2022',
      module: 'ESNext',
      moduleResolution: 'bundler',
      lib: ['ES2022', 'DOM', 'DOM.Iterable'],
      strict: true,
      noEmit: true,
      skipLibCheck: true,
      esModuleInterop: true,
      allowSyntheticDefaultImports: true,
      isolatedModules: true,
      types: ['vite/client'],
    },
    include: ['src'],
  }, null, 2)}\n`;
}

function deployWorkflowYml(archiveBase) {
  return `# Build and publish to GitHub Pages. Generated by Geode's viewer generator --
# see recipe.json in this repo's root for what was requested and
# https://github.com/siwill22/Geode for the tool that built it.
#
# Unlike a hand-built Geode viewer, this repo has no local data of its own:
# every page load fetches live from the shared archive below, so there is
# nothing to download or unpack at build time, and no private submodule.
name: Deploy

on:
  push:
    branches: [main]
  workflow_dispatch:

permissions:
  contents: read
  pages: write
  id-token: write

concurrency:
  group: pages
  cancel-in-progress: true

jobs:
  build:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - uses: actions/setup-node@v4
        with:
          node-version: 22
          cache: npm

      - run: npm ci
      - run: npm run build
        env:
          VITE_BASE: /\${{ github.event.repository.name }}/
          VITE_ARCHIVE_BASE: ${archiveBase}

      - uses: actions/upload-pages-artifact@v3
        with:
          path: dist

  deploy:
    needs: build
    runs-on: ubuntu-latest
    environment:
      name: github-pages
      url: \${{ steps.deployment.outputs.page_url }}
    steps:
      - id: deployment
        uses: actions/deploy-pages@v4
`;
}

function readmeMd(recipe, resolved) {
  const { site } = recipe;
  const coastlineNote = resolved.coastlines.source === 'none'
    ? 'This site has no reconstructed coastline overlay.'
    : `Coastlines are reconstructed against ${resolved.coastlines.reconstructionModel ?? 'the shared plate model'}.`;
  return `# ${site.title}

${site.description ?? ''}

Generated by [Geode](https://github.com/siwill22/Geode)'s viewer generator.
See \`recipe.json\` in this repo for exactly what was requested.

## Data

- **${resolved.modelName}** (\`${resolved.modelId}\`)
- Source: ${resolved.modelSource || 'see the model\'s own manifest'}
- ${coastlineNote}

Data is fetched live from ${recipe.dataHost.archiveBase} on every page load --
this repo carries no copy of it. If that catalog changes (a model is
updated, removed, or corrected), this site's behavior can change without a
redeploy of this repo.

## Development

\`\`\`
npm install
npm run dev
\`\`\`

## License

The code in this repo is MIT-licensed (see \`LICENSE\`). The underlying
data remains under its own source's terms -- see the citation above.
`;
}

