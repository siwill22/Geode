/** Every file under `dir`, as [path relative to `dir`, contents]. */
function filesUnder(dir, prefix = '') {
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const rel = path.posix.join(prefix, e.name);
    if (e.isDirectory()) out.push(...filesUnder(path.join(dir, e.name), rel));
    else out.push([rel, readFileSync(path.join(dir, e.name))]);
  }
  return out;
}

function sha256(buf) {
  return createHash('sha256').update(buf).digest('hex');
}

/** Which Geode wrote a site: the viewer's package version and the commit,
 *  flagged when the checkout had uncommitted changes. */
function geodeVersion(viewerPkg) {
  const git = (...args) => execFileSync('git', ['-C', REPO_ROOT, ...args], { encoding: 'utf8' }).trim();
  try {
    return { version: viewerPkg.version, commit: git('rev-parse', 'HEAD'),
      dirty: git('status', '--porcelain', '--', 'viewer/src', 'viewer/vendor', 'generator') !== '' };
  } catch {
    return { version: viewerPkg.version, commit: null, dirty: null };
  }
}

const STAMP = '.geode/generated.json';
/** The input, not an output: regenerating from an edited recipe is the
 *  point of --update, so it is never a hand edit to refuse over. */
const NOT_CHECKED = new Set(['recipe.json']);

/**
 * @param {string} recipePath
 * @param {string} outDir
 * @param {string} [validateSource] Local archive dir or http(s) URL to
 *   validate against, for this repo's own pre-release testing of a model
 *   not yet on the recipe's real dataHost (see validateRecipe.mjs's
 *   identical parameter), and required for a `dataHost.release` recipe,
 *   whose Archive isn't published until the site is. Never affects what's
 *   WRITTEN into the generated repo.
 * @param {{ update?: boolean, force?: boolean }} [opts]
 */
export async function scaffoldRepo(recipePath, outDir, validateSource, opts = {}) {
  const recipe = loadJson(path.resolve(recipePath));
  const result = await validateRecipe(recipe, validateSource);
  if (!result.ok) {
    throw new Error(`recipe is invalid, run validateRecipe.mjs first:\n${JSON.stringify(result.errors, null, 2)}`);
  }
  const { resolved } = result;

  // Which wrapper directory + HTML entry + generated/config filename this
  // recipe needs -- the only things that differ between wrapperTypes. Each
  // wrapper only ever depends on core/, never on another wrapper directory
  // (see core/tools.ts's doc comment), so exactly one of these gets copied.
  const WRAPPER_DIR = {
    'single-model-globe': 'globe',
    'model-group-globe': 'groupGlobe',
    'single-reconstruction-globe': 'reconstruction',
    'reconstruction-group-globe': 'reconstructionGroup',
    'mantle-globe': 'tomography',
  };
  const HTML_SOURCE = {
    'single-model-globe': 'globe.html',
    'model-group-globe': 'groupGlobe.html',
    'single-reconstruction-globe': 'reconstruction.html',
    'reconstruction-group-globe': 'reconstructionGroup.html',
    'mantle-globe': 'index.html',
  };
  const CONFIG_FILE = {
    'single-model-globe': 'config.ts',
    'model-group-globe': 'groupConfig.ts',
    'single-reconstruction-globe': 'reconstructionConfig.ts',
    'reconstruction-group-globe': 'reconstructionGroupConfig.ts',
    'mantle-globe': 'mantleConfig.ts',
  };
  const CONFIG_SOURCE = {
    'single-model-globe': configTs,
    'model-group-globe': groupConfigTs,
    'single-reconstruction-globe': reconstructionConfigTs,
    'reconstruction-group-globe': reconstructionGroupConfigTs,
    'mantle-globe': mantleConfigTs,
  };
  const wrapperDir = WRAPPER_DIR[recipe.wrapperType];
  const scriptSrc = `/src/${wrapperDir}/main.ts`;

  // Everything the site gets, before any of it is written.
  const files = new Map();
  const emit = (rel, content) => files.set(rel, Buffer.from(content));

  for (const [rel, buf] of filesUnder(path.join(VIEWER_ROOT, 'src', 'core'))) files.set(`src/core/${rel}`, buf);
  for (const [rel, buf] of filesUnder(path.join(VIEWER_ROOT, 'src', wrapperDir))) files.set(`src/${wrapperDir}/${rel}`, buf);
  // core/boundaries.ts imports the vendored petrify JS library
  // unconditionally (see that file) -- copied for every wrapperType, not
  // just the two that use it, so core/ never has a dangling import
  // regardless of which wrapper a future recipe adds it to. Dependency-free
  // and ~36 kB; not worth branching on.
  for (const [rel, buf] of filesUnder(path.join(VIEWER_ROOT, 'vendor', 'petrify', 'js'))) files.set(`vendor/petrify/js/${rel}`, buf);

  let html = readFileSync(path.join(VIEWER_ROOT, HTML_SOURCE[recipe.wrapperType]), 'utf8');
  html = html.replace(/<title>.*<\/title>/, `<title>${escapeHtml(recipe.site.title)}</title>`);
  html = html.replace(scriptSrc, `.${scriptSrc}`);
  emit('index.html', html);
  emit(`src/generated/${CONFIG_FILE[recipe.wrapperType]}`, CONFIG_SOURCE[recipe.wrapperType](recipe, resolved));

  const viewerPkg = loadJson(path.join(VIEWER_ROOT, 'package.json'));
  emit('package.json', packageJson(recipe.site, viewerPkg));
  emit('vite.config.ts', viteConfigTs());
  emit('tsconfig.json', tsconfigJson());
  emit('.github/workflows/deploy.yml', deployWorkflowYml(recipe.dataHost));
  emit('recipe.json', `${JSON.stringify(recipe, null, 2)}\n`);
  emit('README.md', readmeMd(recipe, resolved));
  emit('LICENSE', mitLicense());
  emit('.gitignore', `node_modules/\ndist/\n${recipe.dataHost.release ? 'public/archive/\n' : ''}`);
  if (recipe.dataHost.archiveBase) {
    // The same archive location the deploy workflow sets, so a local
    // `npm run build` produces the site that will actually ship -- without
    // it a local build falls back to /archive on its own origin, which such
    // a repo never has. Not a secret: the URL is public by design. A
    // release-hosted site has no .env: its Archive IS at /archive.
    emit('.env', `# Where this site's data lives -- same value the deploy workflow sets.\n`
      + `VITE_ARCHIVE_BASE=${recipe.dataHost.archiveBase}\n`);
  }

  // Regeneration (docs/adr/0055): refuse to overwrite hand edits.
  const stampPath = path.join(outDir, STAMP);
  const previous = existsSync(stampPath) ? loadJson(stampPath) : null;
  if (previous && !opts.update) {
    throw new Error(`${outDir} is already a generated site (${STAMP}); regenerate it with --update`);
  }
  if (opts.update && !previous && !opts.force) {
    // Sites generated before stamps existed: nothing records what was
    // generated, so nothing can be checked for hand edits. --force adopts
    // one, overwriting every file the generator writes.
    throw new Error(`${outDir} has no ${STAMP}: it predates stamps, or was not generated. `
      + `--update --force adopts it, overwriting every generated file (diff it in git first)`);
  }
  if (previous) {
    const edited = Object.entries(previous.files)
      .filter(([rel]) => !NOT_CHECKED.has(rel))
      .filter(([rel, hash]) => {
        const p = path.join(outDir, rel);
        return !existsSync(p) || sha256(readFileSync(p)) !== hash;
      })
      .map(([rel]) => rel);
    if (edited.length && !opts.force) {
      throw new Error(`these generated files were edited or removed by hand since `
        + `${previous.geode?.commit?.slice(0, 7) ?? 'the last generation'}, and --update would `
        + `overwrite them:\n  ${edited.join('\n  ')}\nMove the change into recipe.json (or Geode `
        + `itself), or pass --force to discard it.`);
    }
    // Generated before, not now (e.g. a file dropped from core/): remove it.
    for (const rel of Object.keys(previous.files)) {
      if (!files.has(rel)) rmSync(path.join(outDir, rel), { force: true });
    }
  }

  for (const [rel, buf] of files) {
    mkdirSync(path.dirname(path.join(outDir, rel)), { recursive: true });
    writeFileSync(path.join(outDir, rel), buf);
  }
  const stamp = {
    note: 'Written by Geode generator/scaffoldRepo.mjs. Regenerate with --update rather than editing the files listed here.',
    geode: geodeVersion(viewerPkg),
    wrapperType: recipe.wrapperType,
    files: Object.fromEntries([...files].map(([rel, buf]) => [rel, sha256(buf)]).sort()),
  };
  mkdirSync(path.dirname(stampPath), { recursive: true });
  writeFileSync(stampPath, `${JSON.stringify(stamp, null, 2)}\n`);

  return { outDir, resolved, changed: previous
    ? [...files].filter(([rel, buf]) => previous.files[rel] !== sha256(buf)).map(([rel]) => rel)
    : [...files.keys()] };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const flags = new Set(args.filter((a) => a.startsWith('--')));
  const [recipePath, outDir, validateSourceArg] = args.filter((a) => !a.startsWith('--'));
  if (!recipePath || !outDir || [...flags].some((f) => !['--update', '--force'].includes(f))) {
    console.error('usage: node generator/scaffoldRepo.mjs recipe.json outDir [validateSource] [--update [--force]]');
    process.exit(2);
  }
  const validateSource = validateSourceArg
    ? (/^https?:\/\//.test(validateSourceArg) ? validateSourceArg : path.resolve(validateSourceArg))
    : undefined;
  try {
    const { resolved, changed } = await scaffoldRepo(recipePath, path.resolve(outDir), validateSource,
      { update: flags.has('--update'), force: flags.has('--force') });
    console.log(`${flags.has('--update') ? 'updated' : 'scaffolded'} ${outDir} (${changed.length} file(s) written with new content)`);
    console.log(JSON.stringify(resolved, null, 2));
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
