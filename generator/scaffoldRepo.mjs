#!/usr/bin/env node
/**
 * Turn a validated Viewer Recipe into a standalone, minimal repo: the
 * generic engine and globe wrapper (viewer/src/core/, viewer/src/globe/),
 * no dev tooling, no private submodule, no local copy of data -- everything
 * else comes from the recipe's own dataHost at runtime. See
 * docs/plans/consider-this-general-question-virtual-kay.md.
 *
 *   node generator/scaffoldRepo.mjs recipe.json outDir [validateSource] [--update [--force]]
 *
 * Generated Sites update by regeneration (docs/adr/0055): every file this
 * writes is recorded, with its hash and the Geode version that wrote it, in
 * the site's .geode/generated.json. `--update` regenerates an existing site
 * in place, and refuses if any recorded file was edited by hand since --
 * those edits would be lost -- unless `--force`, which also adopts a site
 * generated before stamps existed. Files the site added itself are never
 * touched.
 */
import {
  readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, rmSync,
} from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { validateRecipe } from './validateRecipe.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.join(HERE, '..');
const VIEWER_ROOT = path.join(REPO_ROOT, 'viewer');

function loadJson(p) {
  return JSON.parse(readFileSync(p, 'utf8'));
}

function escapeHtml(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

/** `multiGlobe` is offered uniformly across all four wrapper types (see
 *  docs/adr/0022) -- one shared literal-emitter rather than four copies. */
function multiGlobeFieldTs(recipe) {
  return recipe.multiGlobe ? `\n  multiGlobe: ${JSON.stringify(recipe.multiGlobe)},` : '';
}

function configTs(recipe, resolved) {
  return `import type { GlobeTool, MultiGlobeConfig } from '../core/tools';

export interface GlobeConfig {
  modelId: string;
  title: string;
  tools: GlobeTool[];
  multiGlobe?: MultiGlobeConfig;
}

// Generated by generator/scaffoldRepo.mjs from this repo's own recipe.json --
// hand-edit that and re-run the generator rather than editing this file
// directly, or the two will silently disagree.
export const GLOBE_CONFIG: GlobeConfig = {
  modelId: ${JSON.stringify(resolved.modelId)},
  title: ${JSON.stringify(recipe.site.title)},
  tools: ${JSON.stringify(recipe.ui.tools)} as GlobeTool[],${multiGlobeFieldTs(recipe)}
};
`;
}

/** Fixed labels for model-group-globe's two axes -- v1.5 only ever
 *  compares along these two declared manifest fields (reconstruction_model,
 *  comparison_role), so the labels are fixed here rather than being a
 *  recipe field of their own. */
const AXIS_A_LABEL = 'reconstruction';
const AXIS_B_LABEL = 'role';

function groupConfigTs(recipe, resolved) {
  const gridLiteral = {};
  for (const a of resolved.axisA.values) {
    gridLiteral[a] = {};
    for (const b of resolved.axisB.values) gridLiteral[a][b] = resolved.grid[a][b].modelId;
  }
  return `import type { GlobeTool, MultiGlobeConfig } from '../core/tools';

export interface GroupGlobeConfig {
  title: string;
  tools: GlobeTool[];
  multiGlobe?: MultiGlobeConfig;
  axisALabel: string;
  axisBLabel: string;
  grid: Record<string, Record<string, string>>;
  defaultAxisA: string;
  defaultAxisB: string;
}

// Generated by generator/scaffoldRepo.mjs from this repo's own recipe.json --
// hand-edit that and re-run the generator rather than editing this file
// directly, or the two will silently disagree.
export const GROUP_GLOBE_CONFIG: GroupGlobeConfig = {
  title: ${JSON.stringify(recipe.site.title)},
  tools: ${JSON.stringify(recipe.ui.tools)} as GlobeTool[],${multiGlobeFieldTs(recipe)}
  axisALabel: ${JSON.stringify(AXIS_A_LABEL)},
  axisBLabel: ${JSON.stringify(AXIS_B_LABEL)},
  grid: ${JSON.stringify(gridLiteral, null, 2)},
  defaultAxisA: ${JSON.stringify(resolved.defaultAxisA)},
  defaultAxisB: ${JSON.stringify(resolved.defaultAxisB)},
};
`;
}

